
"use client";

import { useState } from "react";
import Link from "next/link";

export default function ReportIncident() {
  const [incidentType, setIncidentType] = useState("");
  const [description, setDescription] = useState("");
  const [incidentDate, setIncidentDate] = useState("");
  const [isOngoing, setIsOngoing] = useState("");
  const [submitted, setSubmitted] = useState(false);
  const [incidentId, setIncidentId] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);
  const [error, setError] = useState("");

  async function handleSubmit(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();
    setIsSubmitting(true);
    setError("");
    setSubmitted(false);
    setIncidentId("");

    try {
      const response = await fetch("/api/incidents", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          incidentType,
          description,
          incidentDate,
          isOngoing,
        }),
      });

      const result = await response.json();

      if (!response.ok) {
        throw new Error(result.error || "Unable to submit incident report");
      }

      setIncidentId(result.id);
      setSubmitted(true);
    } catch (err) {
      setError(err instanceof Error ? err.message : "Please try again.");
    } finally {
      setIsSubmitting(false);
    }
  }

  async function downloadIncidentReport() {
    if (!incidentId) return;

    try {
      const [incidentResponse, evidenceResponse] = await Promise.all([
        fetch("/api/incidents"),
        fetch("/api/evidence"),
      ]);

      if (!incidentResponse.ok || !evidenceResponse.ok) {
        throw new Error("Unable to retrieve incident or evidence details.");
      }

      const incidentData = await incidentResponse.json();
      const evidenceData = await evidenceResponse.json();

      const incident = (incidentData.incidents || []).find(
        (item: any) => item.id === incidentId
      );

      if (!incident) {
        throw new Error("Incident record not found.");
      }

      const linkedEvidence = (evidenceData.evidence || []).filter(
        (item: any) => item.incidentId === incidentId
      );

      const report = [
        "CYBERFIRSTAID - DIGITAL INCIDENT REPORT",
        "======================================",
        "",
        `Incident ID: ${incident.id}`,
        `Incident Type: ${String(incident.incidentType).replace(/_/g, " ")}`,
        `Incident Date: ${incident.incidentDate}`,
        `Status: ${incident.status}`,
        `Still Ongoing: ${incident.isOngoing}`,
        `Created At: ${incident.createdAt}`,
        "",
        "INCIDENT DESCRIPTION",
        "--------------------",
        incident.description,
        "",
        `LINKED DIGITAL EVIDENCE (${linkedEvidence.length})`,
        "------------------------",
        ...linkedEvidence.map((item: any, index: number) =>
          [
            `${index + 1}. ${item.originalName}`,
            `Evidence ID: ${item.id}`,
            `File Type: ${item.fileType}`,
            `File Size: ${item.fileSize} bytes`,
            `SHA-256: ${item.sha256}`,
            `Uploaded At: ${item.uploadedAt}`,
            `Verification status: ${item.status}`,
            "",
          ].join("\n")
        ),
        "",
        "Generated by CyberFirstAid.",
        "This report is an application-generated record.",
      ].join("\n");

      const blob = new Blob([report], {
        type: "text/plain;charset=utf-8",
      });

      const url = URL.createObjectURL(blob);
      const link = document.createElement("a");
      link.href = url;
      link.download = `CyberFirstAid-${incidentId}-report.txt`;
      document.body.appendChild(link);
      link.click();
      link.remove();
      URL.revokeObjectURL(url);
    } catch (downloadError) {
      setError(
        downloadError instanceof Error
          ? downloadError.message
          : "Unable to download incident report."
      );
    }
  }
  return (
    <main className="min-h-screen bg-slate-950 text-white">
      {/* Navigation */}
      <nav className="flex items-center justify-between border-b border-slate-800 px-6 py-5 md:px-16">
        <Link
          href="/"
          className="text-2xl font-bold text-cyan-400"
        >
          CyberFirstAid
        </Link>

        <Link
          href="/"
          className="text-sm text-slate-300 hover:text-cyan-400"
        >
          Back to Home
        </Link>
      </nav>

      {/* Form */}
      <section className="mx-auto max-w-3xl px-6 py-14">
        <div className="mb-10 text-center">
          <h1 className="mb-4 text-4xl font-bold">
            Report a Cyber Incident
          </h1>

          <p className="text-slate-400">
            Tell us what happened so CyberFirstAid can help
            you understand the situation and identify your
            next safety steps.
          </p>
        </div>

        <form
          onSubmit={handleSubmit}
          className="space-y-7 rounded-2xl border border-slate-800 bg-slate-900 p-6 md:p-10"
        >
          {/* Incident Type */}
          <div>
            <label
              htmlFor="incidentType"
              className="mb-2 block font-semibold"
            >
              Type of Cyber Incident
            </label>

            <select
              id="incidentType"
              required
              value={incidentType}
              onChange={(e) => setIncidentType(e.target.value)}
              className="w-full rounded-lg border border-slate-700 bg-slate-800 p-3 text-white"
            >
              <option value="">Select incident type</option>
              <option value="financial_fraud">
                Online Payment / Financial Fraud
              </option>
              <option value="account_hacking">
                Social Media / Account Hacking
              </option>
              <option value="phishing">
                Phishing / Suspicious Link
              </option>
              <option value="identity_theft">
                Identity Theft / Impersonation
              </option>
              <option value="harassment">
                Cyberbullying / Online Harassment
              </option>
              <option value="lost_device">
                Lost or Stolen Device
              </option>
              <option value="other">
                Other Cyber Incident
              </option>
            </select>
          </div>

          {/* Description */}
          <div>
            <label
              htmlFor="description"
              className="mb-2 block font-semibold"
            >
              Describe What Happened
            </label>

            <textarea
              id="description"
              required
              rows={5}
              maxLength={2000}
              value={description}
              onChange={(e) => setDescription(e.target.value)}
              placeholder="Explain what happened in simple words. Do not include passwords, OTPs, PINs or other sensitive details."
              className="w-full rounded-lg border border-slate-700 bg-slate-800 p-3 text-white placeholder:text-slate-400"
            />
          </div>

          {/* Incident Date */}
          <div>
            <label
              htmlFor="incidentDate"
              className="mb-2 block font-semibold"
            >
              When Did It Happen?
            </label>

            <input
              id="incidentDate"
              type="date"
              required
              value={incidentDate}
              max="2099-12-31"
              onChange={(e) => setIncidentDate(e.target.value)}
              className="w-full rounded-lg border border-slate-700 bg-slate-800 p-3 text-white"
            />
          </div>

          {/* Ongoing Incident */}
          <div>
            <label
              htmlFor="isOngoing"
              className="mb-2 block font-semibold"
            >
              Is the Incident Still Ongoing?
            </label>

            <select
              id="isOngoing"
              required
              value={isOngoing}
              onChange={(e) => setIsOngoing(e.target.value)}
              className="w-full rounded-lg border border-slate-700 bg-slate-800 p-3 text-white"
            >
              <option value="">Select an option</option>
              <option value="yes">Yes</option>
              <option value="no">No</option>
              <option value="unsure">Not Sure</option>
            </select>
          </div>

          {/* Privacy Notice */}
          <div className="rounded-lg border border-amber-800 bg-amber-950/40 p-4 text-sm text-amber-200">
            Never share passwords, OTPs, banking PINs,
            recovery codes or sensitive personal information.
            Reports are saved on the application server. This prototype does not yet implement user authentication or access control.
          </div>

          <button
            type="submit"
            disabled={isSubmitting}
            className="w-full rounded-xl bg-cyan-500 py-4 font-bold text-slate-950 transition hover:bg-cyan-400"
          >
            {isSubmitting ? "Submitting..." : "Submit Incident Report"}
          </button>

                    {error && (
            <div role="alert" className="rounded-lg border border-red-700 bg-red-950 p-4 text-center text-red-200">
              {error}
            </div>
          )}

          {submitted && (
            <div role="status" className="rounded-lg border border-cyan-700 bg-cyan-950 p-4 text-center text-cyan-200">
              <p className="font-bold">Incident report saved successfully!</p>
              <p className="mt-2 text-sm">Your Incident ID:</p>
              <p className="mt-1 font-mono text-lg font-bold">{incidentId}</p>
              <p className="mt-2 text-xs">Keep this ID for future reference.</p>
              <button
                type="button"
                onClick={downloadIncidentReport}
                className="mt-5 w-full rounded-xl bg-cyan-500 py-3 font-bold text-slate-950 hover:bg-cyan-400"
              >
                Download Incident Report
              </button>
            </div>
          )}
        </form>
      </section>
    </main>
  );
}


